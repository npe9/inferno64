/*
* beswal is a pure byte-swap the reboot path uses; it is real, not
* a stub.  werrstr formatted an error into a user process's error
* string, which a kernel process does not have, so it does nothing.
*/
ulong beswal(ulong l)
{
uchar *p;
p = (uchar*)&l;
return (p[0]<<24) | (p[1]<<16) | (p[2]<<8) | p[3];
}
