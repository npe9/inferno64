/*
 * QEMU std-vga (Bochs VBE dispi) as a VGAdev for the standard screen.c
 * framework.  No VESA BIOS / real mode: the dispi registers set the mode
 * with plain port I/O, and the linear framebuffer is the card's PCI BAR,
 * mapped by vgalinearpci().  Works under `qemu -kernel`.
 */
#include "u.h"
#include "../port/lib.h"
#include "mem.h"
#include "dat.h"
#include "fns.h"
#include "io.h"

#define	Image	IMAGE
#include <draw.h>
#include <memdraw.h>
#include <cursor.h>
#include "screen.h"

enum {
	VbeIndex	= 0x01CE,
	VbeData		= 0x01CF,

	IdReg		= 0,
	XresReg		= 1,
	YresReg		= 2,
	BppReg		= 3,
	EnableReg	= 4,
	BankReg		= 5,
	VwidthReg	= 6,
	VheightReg	= 7,
	XoffReg		= 8,
	YoffReg		= 9,

	Disabled	= 0x00,
	Enabled		= 0x01,
	Lfb		= 0x40,
	Noclear		= 0x80,
};

static void
vbew(int idx, int val)
{
	outs(VbeIndex, idx);
	outs(VbeData, val);
}

/*
 * Write-combining MTRR is only a performance hint; the nix kernel has no
 * MTRR support, so stub it (screen.c's vgalinearaddr calls it).
 */
int
mtrr(uvlong base, uvlong size, char *type)
{
	USED(base); USED(size); USED(type);
	return 0;
}

/*
 * libmemdraw's image pool spinlock uses _tas; nix's kernel test-and-set
 * is tas32.  Bridge them.
 */
int
_tas(void *p)
{
	return tas32(p);
}

/*
 * screenaperture() (unused by the linear bochs path) wants a UPA
 * allocator the nix kernel does not provide; stub it to fail cleanly.
 */
uintptr
upamalloc(uintptr addr, usize size, usize align)
{
	USED(addr); USED(size); USED(align);
	return 0;
}

static void
bochsmode(int w, int h, int d)
{
	vbew(EnableReg, Disabled);
	vbew(XresReg, w);
	vbew(YresReg, h);
	vbew(BppReg, d);
	vbew(BankReg, 0);
	vbew(VwidthReg, w);
	vbew(VheightReg, h);
	vbew(XoffReg, 0);
	vbew(YoffReg, 0);
	vbew(EnableReg, Enabled|Lfb);
}

static void
bochsenable(VGAscr *scr)
{
	if(scr->pci == nil)
		vgalinearpciid(scr, 0x1234, 0x1111);	/* map the LFB */
}

/*
 * A non-nil linear method marks this as a linear-framebuffer driver;
 * screen.c's swcursorinit() refuses to run the software cursor without
 * it.  The aperture is already mapped by vgalinearpci in bochsenable.
 */
static void
bochslinear(VGAscr *scr, int, int)
{
	if(scr->paddr == 0)
		vgalinearpciid(scr, 0x1234, 0x1111);
}

VGAdev vgabochsdev = {
	"bochs",
	bochsenable,		/* enable */
	nil,			/* disable */
	nil,			/* page */
	bochslinear,		/* linear */
	nil,			/* drawinit */
	nil,			/* fill */
	nil,			/* ovlctl */
	nil,			/* ovlwrite */
	nil,			/* flush (nil => draw straight to the LFB) */
};

/*
 * Driver tables normally generated by the config's vga link section.
 * We only support the QEMU std-vga plus the portable software cursor.
 */
extern VGAcur swcursor;
VGAdev* vgadev[] = {
	&vgabochsdev,
	nil,
};
VGAcur* vgacur[] = {
	&swcursor,
	nil,
};

/*
 * Bring up a default graphics screen at boot so /dev/draw works without
 * the userspace aux/vga.  Called when the draw device is first attached
 * (process context: screensize and vgalinearpci can error()).
 */
void
bochsscreeninit(void)
{
	VGAscr *scr;
	int w, h, d;

	w = 1024; h = 768; d = 32;
	scr = &vgascreen[0];
	scr->dev = &vgabochsdev;

	bochsmode(w, h, d);

	if(waserror()){
		print("bochsscreeninit: %s\n", up->errstr);
		return;
	}
	vgalinearpciid(scr, 0x1234, 0x1111);
	screensize(w, h, d, XRGB32);
	poperror();

	/*
	 * The software cursor is enabled the standard way, from userspace:
	 *   echo hwgc soft > /dev/vgactl
	 * (QEMU std-vga has no hardware cursor sprite.)
	 */
	print("bochs: /dev/draw screen %dx%dx%d at va %#p pa %#p\n",
		w, h, d, scr->vaddr, (void*)scr->paddr);
}
