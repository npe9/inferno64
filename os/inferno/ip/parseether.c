/*
 * From os/9front/lib/parseether.c.  A kernel here builds it as kernel source
 * rather than linking the hosted libip, which os/inferno/port/
 * portmkfile would otherwise fetch from $ROOT/libip: its
 * readipifc.c opens and reads /net/ipifc.
 */
#include	"u.h"
#include	"../port/lib.h"
#include	"mem.h"
#include	"dat.h"
#include	"fns.h"
#include	"../port/error.h"

int
parseether(uchar *to, char *from)
{
	char nip[4];
	char *p;
	int i;

	p = from;
	for(i = 0; i < 6; i++){
		if(*p == 0)
			return -1;
		nip[0] = *p++;
		if(*p == 0)
			return -1;
		nip[1] = *p++;
		nip[2] = 0;
		to[i] = strtoul(nip, 0, 16);
		if(*p == ':')
			p++;
	}
	return 0;
}
