#
# The hardware boundary: files.
#
# This is a correction.  The first version of this interface was a
# module whose PATH was a .dis, with battmv(), rgb(), radiosend() and
# the rest as function calls.  That is real Limbo and it is not how
# Inferno reaches hardware.  Inferno has two mechanisms and that was
# neither:
#
#	a device serves files and Limbo opens them -- appl/lib/daytime.b
#	reading /dev/time is the pattern, and this tree already carries
#	os/inferno/port/devi2c.c (#J) for exactly the I2C parts a
#	PyCubed has;
#
#	or a module implemented in C inside libinterp, declared with
#	PATH: con "$Name" (module/math.m, module/keyring.m), listed in
#	the kernel conf's mod section and generated by limbo -T.  That
#	one is for things like Math and Keyring, not for device access.
#
# A .dis PATH can only ever be satisfied by a Limbo implementation, so
# the old interface could not have been met by the C drivers phase 2 of
# doc/pycubed-plan.ms describes.  The boundary is now the file protocol
# below, and what follows in this file is only a Limbo library that
# opens those files -- which is why its PATH is a .dis and correctly so.
#
# The protocol.  One directory, named by open(), holding:
#
#	battery   read   "<millivolts>\n"
#	rgb       write  "<r> <g> <b>"        0..255 each
#	torque    write  "<x> <y> <z>"        milli-A.m^2, signed
#	          read   the dipole in force
#	imu       read   "mag <x> <y> <z>\n"
#	                 "gyro <x> <y> <z>\n"
#	                 "accel <x> <y> <z>\n"
#	                 milli-units throughout: milli-gauss for the
#	                 magnetometer, milli-degrees a second for the
#	                 gyroscope, milli-g for the accelerometer.  The
#	                 gyroscope line is spelled out because both
#	                 halves of the stm32f407 driver reported whole
#	                 degrees for a while, which put the scripted
#	                 model's noise three orders of magnitude out and
#	                 hid a working controller.

# The radio is a file, not a Medium at /net/ether0: ssl(3) attaches to a
# file descriptor, so Styx over an authenticated, encrypted link needs
# no IP stack under it.  See doc/pycubed-plan.ms and radio(3).
#
#	radio0    write  one write is one packet
#	                 read  one read is one packet
#
# haveradio() answers whether #W/radio0/data opened.  On a board with no
# radio fitted -- which is every board in this tree except mps2 under a
# QEMU with "-machine radio=on" -- it answers 0 and beacon() says so
# rather than pretending to transmit.
#
# Text, and integers rather than reals, because the parts this is for
# have no double-precision floating point (doc/armv7m-ports.ms) and
# because a file you can cat is the point of the file interface.
#
# On a real board the C drivers of phase 2 serve these as part of /dev.
# On a board with none of the hardware, os/inferno/mps2/archfiles.c
# registers them through addarchfile() and /dev/arch says that every
# reading is invented.
#

Hw: module
{
	PATH:	con "/dis/pycubed/hw.dis";

	init:		fn(dir: string): string;	# nil, or why not
	source:		fn(): string;		# where the readings come from

	battmv:		fn(): int;
	rgb:		fn(r, g, b: int);
	haveradio:	fn(): int;
	radiosend:	fn(b: array of byte): int;
	# One read, one packet, and it BLOCKS until one arrives -- which
	# is why its caller is a process of its own and not a poll in
	# somebody's timer loop.  The protocol above always said the
	# radio file reads as well as writes; nothing read it, so the
	# satellite could beacon and could not be told anything, and
	# cdh() sat in beepsat.b with no caller.
	radiorecv:	fn(b: array of byte): int;
	# The magnetorquers, as a commanded dipole in milli-A.m^2.  An
	# actuator, which this interface did not have: the mission could
	# read the IMU and never change it, which makes a sensor a
	# fixture rather than something to control.
	torque:		fn(x, y, z: int): int;

	imumag:		fn(): array of int;
	imugyro:	fn(): array of int;
	imuaccel:	fn(): array of int;
};
